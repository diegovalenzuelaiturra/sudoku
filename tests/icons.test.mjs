import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

import { PNG_ICONS, SOURCE_SHA256, svgHash } from '../scripts/icons.mjs';

const root = join(import.meta.dirname, '..');

test('the raster icons were generated from the current icon.svg', () => {
  assert.notEqual(
    SOURCE_SHA256,
    'PLACEHOLDER',
    'scripts/icons.mjs has never been run; run npm run icons',
  );
  assert.equal(
    svgHash(),
    SOURCE_SHA256,
    'icons/icon.svg changed but the PNGs were not regenerated. Run npm run icons. ' +
      'Do not edit SOURCE_SHA256 by hand, that only hides the drift.',
  );
});

test('icons.mjs renders exactly the rasters the manifest declares and nothing else sits beside them', () => {
  assert.ok(PNG_ICONS.length > 0, 'manifest.webmanifest declares no image/png icon');

  const rendered = PNG_ICONS.map(({ src }) => src).toSorted();
  const manifest = JSON.parse(readFileSync(join(root, 'manifest.webmanifest'), 'utf8'));
  const declared = manifest.icons
    .map(({ src }) => src)
    .filter((src) => src.toLowerCase().endsWith('.png'))
    .toSorted();
  assert.deepEqual(rendered, declared, 'every .png icon in the manifest must be typed image/png');

  const onDisk = readdirSync(join(root, 'icons'))
    .filter((name) => name.toLowerCase().endsWith('.png'))
    .map((name) => `icons/${name}`)
    .toSorted();
  assert.deepEqual(
    onDisk,
    rendered,
    'a PNG the manifest does not declare is never regenerated by npm run icons, ' +
      'so it goes stale beside icon.svg while the hash test passes',
  );

  for (const { src, size } of PNG_ICONS) {
    const file = join(root, src);
    assert.ok(existsSync(file), `${src} is missing`);

    /* Read width and height straight out of the PNG IHDR rather than trusting
       the filename: signature, then a 4 byte length, then "IHDR", then w and h
       as big endian uint32. */
    const bytes = readFileSync(file);
    assert.equal(bytes.subarray(0, 8).toString('hex'), '89504e470d0a1a0a', `${src} is not a PNG`);
    assert.equal(bytes.subarray(12, 16).toString('ascii'), 'IHDR', `${src} has no IHDR`);
    assert.equal(bytes.readUInt32BE(16), size, `${src} is not ${size} wide`);
    assert.equal(bytes.readUInt32BE(20), size, `${src} is not ${size} tall`);
  }
});
